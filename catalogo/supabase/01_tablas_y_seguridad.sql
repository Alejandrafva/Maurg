-- Mantener el stock total = suma del stock por color (cuando hay stock por color).
create or replace function public.productos_antes_de_guardar() returns trigger
language plpgsql set search_path = public as $$
declare total integer;
begin
  if new.stock_color is null or jsonb_typeof(new.stock_color) <> 'object' then
    new.stock_color := '{}'::jsonb;
  end if;
  if new.stock_color <> '{}'::jsonb
     and (tg_op = 'INSERT' or new.stock_color is distinct from old.stock_color) then
    select coalesce(sum(greatest(0, coalesce((value)::text, '0')::numeric)), 0)::int
      into total from jsonb_each_text(new.stock_color);
    new.stock := total;
  end if;
  new.stock := greatest(0, coalesce(new.stock, 0));
  new.actualizado := now();
  return new;
end $$;

drop trigger if exists productos_antes_de_guardar on public.productos;
create trigger productos_antes_de_guardar
  before insert or update on public.productos
  for each row execute function public.productos_antes_de_guardar();

