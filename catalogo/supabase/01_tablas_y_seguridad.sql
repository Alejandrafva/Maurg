-- Al entrar un pedido: siempre "pendiente", con la hora real; frena el
-- abuso (máx. 30 pedidos en 10 minutos) y limpia los pedidos viejos.
create or replace function public.pedidos_al_entrar() returns trigger
language plpgsql security definer set search_path = public as $$
declare dias integer; recientes integer;
begin
  new.estado := 'pendiente';
  new.creado := now();
  select count(*) into recientes from public.pedidos where creado > now() - interval '10 minutes';
  if recientes >= 30 then
    raise exception 'Demasiados pedidos seguidos. Intenta en unos minutos.';
  end if;
  select coalesce(nullif(datos->>'diasPedidos','')::int, 30) into dias from public.config where id = 1;
  delete from public.pedidos where creado < now() - make_interval(days => greatest(1, coalesce(dias, 30)));
  return new;
end $$;

drop trigger if exists pedidos_al_entrar on public.pedidos;
create trigger pedidos_al_entrar
  before insert on public.pedidos
  for each row execute function public.pedidos_al_entrar();

-- Aceptar un pedido: descuenta stock (por color si lo hay) y lo borra.
-- p_items es opcional: si el administrador editó el pedido, se usan esos.
create or replace function public.aceptar_pedido(p_id uuid, p_items jsonb default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  ped public.pedidos;
  it jsonb;
  lista jsonb;
  pid bigint;
  col text;
  cant integer;
  hechos integer := 0;
begin
  if not public.es_admin() then
    raise exception 'Solo el administrador puede aceptar pedidos';
  end if;
  select * into ped from public.pedidos where id = p_id for update;
  if not found then
    raise exception 'El pedido ya no existe';
  end if;
  lista := coalesce(p_items, ped.items);
  for it in select * from jsonb_array_elements(lista) loop
    pid := nullif(it->>'id','')::bigint;
    col := nullif(it->>'color','');
    cant := greatest(0, coalesce(nullif(it->>'cantidad','')::int, 0));
    continue when pid is null or cant = 0;
    update public.productos p set
      stock_color = case
        when col is not null and p.stock_color ? col
          then jsonb_set(p.stock_color, array[col], to_jsonb(greatest(0, coalesce((p.stock_color->>col)::numeric, 0)::int - cant)))
        else p.stock_color end,
      stock = case
        when col is not null and p.stock_color ? col then p.stock
        else greatest(0, p.stock - cant) end
    where p.id = pid;
    hechos := hechos + 1;
  end loop;
  delete from public.pedidos where id = p_id;
  return jsonb_build_object('ok', true, 'productos', hechos, 'pdf_url', ped.pdf_url);
end $$;

-- Limpieza manual (el almacén la llama al abrir): borra pedidos viejos.
create or replace function public.limpiar_pedidos_viejos() returns integer
language plpgsql security definer set search_path = public as $$
declare dias integer; n integer;
begin
  if not public.es_admin() then return 0; end if;
  select coalesce(nullif(datos->>'diasPedidos','')::int, 30) into dias from public.config where id = 1;
  delete from public.pedidos where creado < now() - make_interval(days => greatest(1, coalesce(dias, 30)));
  get diagnostics n = row_count;
  return n;
end $$;

-- =====================================================================
-- 5) SEGURIDAD (RLS)
--    Cualquiera puede LEER el catálogo y los ajustes.
--    Cualquiera puede ENVIAR un pedido (queda pendiente).
--    SOLO el administrador (es_admin) crea, edita o borra.
-- =====================================================================
alter table public.productos enable row level security;
alter table public.productos_privado enable row level security;
alter table public.proveedores enable row level security;
alter table public.config enable row level security;
alter table public.pedidos enable row level security;

-- productos
drop policy if exists "productos: leer" on public.productos;
drop policy if exists "productos: admin crea" on public.productos;
drop policy if exists "productos: admin edita" on public.productos;
drop policy if exists "productos: admin borra" on public.productos;
create policy "productos: leer" on public.productos for select using (true);
create policy "productos: admin crea" on public.productos for insert to authenticated with check (public.es_admin());
create policy "productos: admin edita" on public.productos for update to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "productos: admin borra" on public.productos for delete to authenticated using (public.es_admin());

